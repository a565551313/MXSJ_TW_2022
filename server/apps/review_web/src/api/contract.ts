export type QueryValue = string | number | boolean | null | undefined

/** Drops empty/undefined params so the URL only carries what the caller asked for. */
export function buildQuery(params: Record<string, QueryValue>): string {
  const search = new URLSearchParams()
  for (const [key, value] of Object.entries(params)) {
    if (value === null || value === undefined) continue
    const text = String(value)
    if (text.length === 0) continue
    search.set(key, text)
  }
  const query = search.toString()
  return query.length > 0 ? `?${query}` : ''
}

/** 1-based page/page_size (UI) -> offset/limit (API). */
export function pageToOffset(page: number, pageSize: number): number {
  const safePage = Number.isFinite(page) && page > 0 ? Math.floor(page) : 1
  const safeSize = clampLimit(pageSize)
  return (safePage - 1) * safeSize
}

export function clampLimit(limit: number): number {
  if (!Number.isFinite(limit)) return DEFAULT_PAGE_SIZE
  return Math.min(MAX_LIMIT, Math.max(1, Math.floor(limit)))
}

export function offsetToPage(offset: number, limit: number): number {
  const safeLimit = clampLimit(limit)
  return Math.floor(Math.max(0, offset) / safeLimit) + 1
}
